function setText(selector, text) {
  const element = document.querySelector(selector);
  if (element) element.textContent = text;
}

function setTextList(selector, texts) {
  document.querySelectorAll(selector).forEach((element, index) => {
    if (texts[index] !== undefined) element.textContent = texts[index];
  });
}

function applyCardTriples(selector, triples) {
  document.querySelectorAll(selector).forEach((card, index) => {
    const data = triples[index];
    if (!data) return;
    const label = card.querySelector(".card-index, span");
    const heading = card.querySelector("h3");
    const copy = card.querySelector("p");
    if (label) label.textContent = data[0];
    if (heading) heading.textContent = data[1];
    if (copy) copy.textContent = data[2];
  });
}

